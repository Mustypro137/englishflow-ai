import { defineVocabulary } from "../schemas";

type Pos = "noun" | "verb" | "adjective" | "adverb" | "phrase" | "preposition";

function w(
  topic: string,
  headword: string,
  partOfSpeech: Pos,
  definition: string,
  examples: [string, string, ...string[]],
  collocations: string[],
  cloze: [string, ...string[]],
  extra: {
    ipa?: string;
    usageNote?: string;
    commonErrors?: { wrong: string; right: string; why: string }[];
    accepted?: string[];
  } = {},
) {
  const [clozeText, ...rest] = cloze;
  return {
    slug: `a1-${headword
      .normalize("NFD")
      .replaceAll(/[̀-ͯ]/g, "")
      .toLowerCase()
      .replaceAll(/[^a-z]+/g, "-")
      .replace(/-$/, "")}`,
    headword,
    partOfSpeech,
    topic,
    definition,
    examples,
    collocations,
    cloze: { text: clozeText, accepted: extra.accepted ?? (rest.length ? rest : [headword]) },
    ipa: extra.ipa,
    usageNote: extra.usageNote,
    commonErrors: extra.commonErrors,
  };
}

